export async function togglePublish(id: string, publish: boolean) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return { error: "Not authenticated" };

  const { error } = await supabase
    .from("listings")
    .update({ is_published: publish })
    .eq("id", id);

  if (error) return { error: error.message };

  await supabase.from("activity_logs").insert({
    user_id: user.id,
    action: publish ? "listing_published" : "listing_unpublished",
    entity_type: "listing",
    entity_id: id,
  });

  // Fire webhook when publishing
  if (publish) {
    const { data: listing } = await supabase
      .from("listings")
      .select("*")
      .eq("id", id)
      .single();

    const payload = {
      event: "listing.published",
      listing_id: listing?.id,
      listing,
    };

    // Internal logging webhook
    try {
      const baseUrl = process.env.NEXT_PUBLIC_SITE_URL || "";
      await fetch(`${baseUrl}/api/webhooks/listing-published`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-webhook-secret": process.env.WEBHOOK_SECRET || "",
        },
        body: JSON.stringify(payload),
      }).catch(() => {});
    } catch {
      // non-blocking
    }

    // n8n automation webhook
    fireN8nWebhook(payload);
  }

  revalidatePath("/listings");
  return { success: true };
}

export async function deleteListing(id: string) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return { error: "Not authenticated" };

  const { error } = await supabase.from("listings").delete().eq("id", id);

  if (error) return { error: error.message };

  await supabase.from("activity_logs").insert({
    user_id: user.id,
    action: "listing_deleted",
    entity_type: "listing",
    entity_id: id,
  });

  revalidatePath("/listings");
  return { success: true };
}
